local function __require(target)
	if type(target) == "table" and rawget(target, "_isModule") then
		if __cache[target] ~= nil then
			return __cache[target].Value
		end
		if __loading[target] then
			error("[AetherUI bundle] circular require: " .. tostring(rawget(target, "Name")))
		end
		__loading[target] = true
		local value = __defs[target](target, __require)
		__loading[target] = nil
		__cache[target] = { Value = value }
		return value
	end
	return require(target)
end

