		Metrics = { FPS = 60, Ping = 0, Memory = 0, Uptime = 0 },
		MetricsChanged = Utils.Signal.new(),
	}
	self.Ctx = ctx
	self.Settings = ctx.Settings
	self.Maid:Give(ctx.MetricsChanged)

