	self.Live = config.Live ~= false
	self.Value = ""
	self.Disabled = false
	self.Searchable = false

	local height = config.Height or (ctx.ControlHeight + (inline and 0 or 8))
	local holder = Utils.Create("Frame", {
		Name = "SearchBar",
		Size = config.Size or UDim2.new(1, 0, 0, height),
