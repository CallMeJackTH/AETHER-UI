	local node = setmetatable({
		Name = name,
		Parent = parent,
		ClassName = isModule and "ModuleScript" or "Folder",
		_children = {},
		_isModule = isModule,
	}, Node)
	if parent then
		table.insert(rawget(parent, "_children"), node)
