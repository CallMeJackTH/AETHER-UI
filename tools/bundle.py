#!/usr/bin/env python3
"""Build the standalone AETHER UI bundle from src/ modules.

Run from any working directory:
    python tools/bundle.py

The script intentionally uses a stable module order so generated bundles are
reproducible and easy to diff.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
OUTPUT = ROOT / "build" / "AetherUI.lua"

ROOT_MODULES = [
    "Animation",
    "Components",
    "ConfigManager",
    "Core",
    "ESP",
    "Notifications",
    "Overlay",
    "Pages",
    "Sidebar",
    "Theme",
    "Utils",
    "Window",
]

COMPONENT_MODULES = [
    "Button",
    "ColorPicker",
    "Divider",
    "Dropdown",
    "Keybind",
    "Label",
    "MultiDropdown",
    "Paragraph",
    "Slider",
    "Textbox",
    "Toggle",
]


def read_module(path: Path) -> str:
    if not path.is_file():
        raise FileNotFoundError(f"Missing source module: {path.relative_to(ROOT)}")
    return path.read_text(encoding="utf-8").rstrip() + "\n"


def build() -> str:
    lines = [
        "--[[",
        "    AETHER UI - bundled build (generated by tools/bundle.py, do not edit)",
        "",
        "    Usage:",
        '        local Library = loadstring(game:HttpGet("https://raw.githubusercontent.com/CallMeJackTH/AETHER-UI/main/build/AetherUI.lua"))()',
        '        local Window = Library:CreateWindow({ Title = "AETHER", Size = Vector2.new(650, 420) })',
        "",
        "    Modules: " + ", ".join(ROOT_MODULES) + ", Components/" + ", ".join(COMPONENT_MODULES),
        "]]",
        "",
        "local __defs = {}",
        "local __cache = {}",
        "local __loading = {}",
        "local __nodes = {}",
        "",
        "local Node = {}",
        "Node.__index = function(self, key)",
        "\tlocal method = Node[key]",
        "\tif method ~= nil then",
        "\t\treturn method",
        "\tend",
        "\tlocal children = rawget(self, \"_children\")",
        "\tfor _, child in ipairs(children) do",
        "\t\tif rawget(child, \"Name\") == key and rawget(child, \"_isModule\") then",
        "\t\t\treturn child",
        "\t\tend",
        "\tend",
        "\tfor _, child in ipairs(children) do",
        "\t\tif rawget(child, \"Name\") == key then",
        "\t\t\treturn child",
        "\t\tend",
        "\tend",
        "\treturn nil",
        "end",
        "",
        "function Node:GetChildren()",
        "\treturn table.clone(rawget(self, \"_children\"))",
        "end",
        "",
        "function Node:FindFirstChild(name)",
        "\treturn self[name]",
        "end",
        "",
        "function Node:WaitForChild(name)",
        "\treturn self[name]",
        "end",
        "",
        "function Node:IsA(className)",
        "\tif className == \"Instance\" then",
        "\t\treturn true",
        "\tend",
        "\tif rawget(self, \"_isModule\") then",
        "\t\treturn className == \"ModuleScript\"",
        "\tend",
        "\treturn className == \"Folder\"",
        "end",
        "",
        "local function __node(name, parent, isModule)",
        "\tlocal node = setmetatable({",
        "\t\tName = name,",
        "\t\tParent = parent,",
        "\t\tClassName = isModule and \"ModuleScript\" or \"Folder\",",
        "\t\t_children = {},",
        "\t\t_isModule = isModule,",
        "\t}, Node)",
        "\tif parent then",
        "\t\ttable.insert(rawget(parent, \"_children\"), node)",
        "\tend",
        "\treturn node",
        "end",
        "",
        "local function __require(target)",
        "\tif type(target) == \"table\" and rawget(target, \"_isModule\") then",
        "\t\tif __cache[target] ~= nil then",
        "\t\t\treturn __cache[target].Value",
        "\t\tend",
        "\t\tif __loading[target] then",
        "\t\t\terror(\"[AetherUI bundle] circular require: \" .. tostring(rawget(target, \"Name\")))",
        "\t\tend",
        "\t\t__loading[target] = true",
        "\t\tlocal value = __defs[target](target, __require)",
        "\t\t__loading[target] = nil",
        "\t\t__cache[target] = { Value = value }",
        "\t\treturn value",
        "\tend",
        "\treturn require(target)",
        "end",
        "",
        'local __root = __node("AETHER-UI", nil, true)',
    ]

    for name in ROOT_MODULES:
        lines.append(f'local __mod_{name} = __node("{name}", __root, true)')

    lines.append('local __folder_Components = __node("Components", __root, false)')
    for name in COMPONENT_MODULES:
        lines.append(f'local __mod_Components_{name} = __node("{name}", __folder_Components, true)')

    for name in ROOT_MODULES:
        lines.extend([
            "",
            f"-- {name}.lua",
            f"__defs[__mod_{name}] = function(script, require)",
            read_module(SRC / f"{name}.lua").rstrip(),
            "end",
        ])

    for name in COMPONENT_MODULES:
        lines.extend([
            "",
            f"-- Components/{name}.lua",
            f"__defs[__mod_Components_{name}] = function(script, require)",
            read_module(SRC / "Components" / f"{name}.lua").rstrip(),
            "end",
        ])

    lines.extend(["", "return __require(__root)", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"Built {OUTPUT.relative_to(ROOT)}")
