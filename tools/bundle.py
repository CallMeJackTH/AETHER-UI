#!/usr/bin/env python3
"""
Bundles AETHER-UI/src into one self-contained script: build/AetherUI.lua

Every module is wrapped in `function(script, require) ... end` and executed
lazily through a tiny virtual instance tree (Parent / children / FindFirstChild /
GetChildren / IsA), so the sources keep using `require(script.Parent.X)`
unchanged. The bundle returns what src/init.lua returns.

usage: python3 tools/bundle.py            (run from AETHER-UI/)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(ROOT, "build", "AetherUI.lua")

HEADER = '''--[[
	AETHER UI  -  bundled build (generated by tools/bundle.py, do not edit)

	Usage:
	    local Library = loadstring(game:HttpGet("https://raw.githubusercontent.com/<user>/<repo>/main/build/AetherUI.lua"))()
	    local Window = Library:CreateWindow({ Title = "AETHER", Size = Vector2.new(650, 420) })

	Modules: %s
]]

local __defs = {}
local __cache = {}
local __loading = {}
local __nodes = {}

local Node = {}
Node.__index = function(self, key)
	local method = Node[key]
	if method ~= nil then
		return method
	end
	local children = rawget(self, "_children")
	for _, child in ipairs(children) do
		if rawget(child, "Name") == key and rawget(child, "_isModule") then
			return child
		end
	end
	for _, child in ipairs(children) do
		if rawget(child, "Name") == key then
			return child
		end
	end
	return nil
end

function Node:GetChildren()
	return table.clone(rawget(self, "_children"))
end

function Node:FindFirstChild(name)
	return self[name]
end

function Node:WaitForChild(name)
	return self[name]
end

function Node:IsA(className)
	if className == "Instance" then
		return true
	end
	if rawget(self, "_isModule") then
		return className == "ModuleScript"
	end
	return className == "Folder"
end

local function __node(name, parent, isModule)
	local node = setmetatable({
		Name = name,
		Parent = parent,
		ClassName = isModule and "ModuleScript" or "Folder",
		_children = {},
		_isModule = isModule,
	}, Node)
	if parent then
		table.insert(rawget(parent, "_children"), node)
	end
	return node
end

local function __require(target)
	if type(target) == "table" and rawget(target, "_isModule") then
		if __cache[target] ~= nil then
			return __cache[target].Value
		end
		if __loading[target] then
			error("[AetherUI bundle] circular require: " .. tostring(rawget(target, "Name")))
		end
		__loading[target] = true
		local value = __defs[target](target, __require)
		__loading[target] = nil
		__cache[target] = { Value = value }
		return value
	end
	return require(target)
end

local __root = __node("AETHER-UI", nil, true)
'''

FOOTER = '''
return __require(__root)
'''


def collect():
    files = []
    for dirpath, _dirs, names in os.walk(SRC):
        for name in names:
            if name.endswith(".lua"):
                full = os.path.join(dirpath, name)
                rel = os.path.relpath(full, SRC).replace(os.sep, "/")
                files.append(rel)
    files.sort(key=lambda r: (r.count("/"), r))
    return files


def main():
    files = collect()
    if "init.lua" not in files:
        sys.exit("src/init.lua is missing")

    parts = [HEADER % ", ".join(f[:-4] for f in files if f != "init.lua")]
    folders = {}

    def folder_var(path):
        if path in folders:
            return folders[path]
        var = "__folder_" + path.replace("/", "_")
        folders[path] = var
        parts.append('local %s = __node("%s", __root, false)\n' % (var, path.split("/")[-1]))
        return var

    for rel in files:
        with open(os.path.join(SRC, rel), "r", encoding="utf8") as handle:
            source = handle.read().replace("\r\n", "\n").rstrip() + "\n"

        pieces = rel[:-4].split("/")
        if rel == "init.lua":
            var = "__root"
        else:
            parent = "__root" if len(pieces) == 1 else folder_var("/".join(pieces[:-1]))
            var = "__mod_" + "_".join(pieces)
            parts.append('local %s = __node("%s", %s, true)\n' % (var, pieces[-1], parent))

        parts.append("-- %s\n__defs[%s] = function(script, require)\n%s\nend\n\n" % (rel, var, source))

    parts.append(FOOTER)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf8", newline="\n") as handle:
        handle.write("".join(parts))
    print("wrote %s (%d modules, %d bytes)" % (os.path.relpath(OUT, ROOT), len(files), os.path.getsize(OUT)))


if __name__ == "__main__":
    main()
