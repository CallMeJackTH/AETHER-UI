local Aether = require(game.ReplicatedStorage.AETHER_UI)
local Window = Aether:CreateWindow({Title="AETHER UI",Subtitle="Advanced Example",Theme="Midnight",Acrylic=true})
local Main = Window:CreateTab({Name="Controls"})
local General = Main:CreateSection("Runtime")
local modules = General:CreateMultiDropdown({Name="Modules",Options={"Visuals","Audio","Movement"},Default={"Visuals"},Callback=function(v) print(table.concat(v,", ")) end})
General:CreateKeybind({Name="Toggle key",Default=Enum.KeyCode.RightShift,Callback=function(key) print("Key:",key.Name) end})
General:CreateColorPicker({Name="Accent",Default=Color3.fromRGB(168,181,255),Callback=function(color) print(color) end})
General:CreateProgressBar({Name="Download",Value=62})
General:CreateSearchBar({Name="Find command",Callback=function(query) print("Search:",query) end})
General:CreateThemeManager()
General:CreateConfigurationManager({ConfigName="Advanced"})
General:CreateModal({Name="Confirm reset",Title="Reset settings?",Content="This is a sample confirmation.",Callback=function() print("Confirmed") end})
