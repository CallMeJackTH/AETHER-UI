local Aether = require(game.ReplicatedStorage.AETHER_UI)
local Window = Aether:CreateWindow({Title="AETHER UI",Subtitle="Basic Example",Size=UDim2.fromOffset(600,440),Acrylic=true,Theme="Dark"})
local Tab = Window:CreateTab({Name="Main",Icon="house"})
local Section = Tab:CreateSection("General")
Section:CreateButton({Name="Example",Description="Run a simple callback.",Callback=function() print("Clicked") end})
Section:CreateToggle({Name="Enabled",Default=false,Callback=function(value) print("Enabled:",value) end})
Section:CreateSlider({Name="Volume",Min=0,Max=100,Default=65,Callback=function(value) print("Volume:",value) end})
Section:CreateDropdown({Name="Mode",Options={"Performance","Balanced","Quality"},Default="Balanced",Callback=print})
Section:CreateTextbox({Name="Player name",Placeholder="Enter a name",Callback=print})
